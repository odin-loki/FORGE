"""spec -> GPU kernels (FORGE_PLAN Part B.4: Vulkan/Metal kernels come from the spec generator).

Emits, for the spec ops that have a GPU lowering below:
  * one GLSL compute shader per kernel (compiled to SPIR-V by glslangValidator, validated by spirv-val,
    embedded into the binary and run through the Vulkan backend), and
  * one CUDA/HIP single-source file (compiled to PTX / AMDGCN by clang as a compile check).
Every emitted kernel must name an op present in spec/ops/*.fspec, so the GPU set can never drift from the spec.
"""
