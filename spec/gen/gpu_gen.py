def msl(names):
    import re
    body = cuda(names).replace(CU_PRELUDE, "").replace(CU_MATH, "")
    body = body.replace("double th = (double)pos[s] * (double)inv[j]", "float th = pos[s] * inv[j]")
    body = body.replace("__builtin_bit_cast(unsigned, ", "as_type<uint>(").replace("-__builtin_inff()", "-INFINITY")
    body = body.replace("FORGE_DEV float kvat(const float* base", "static inline float kvat(device const float* base")
    body = body.replace("FORGE_DEV", "static inline")
    def sig(m):
        params = [p.strip() for p in m.group(2).split(",")]
        out = []
        for i, p in enumerate(params):
            if "*" in p: out.append(f"device {p} [[buffer({i})]]")
            else:
                t, n = p.rsplit(" ", 1); t = "uint" if t == "unsigned" else t
                out.append(f"constant {t}& {n} [[buffer({i})]]")
        out.append("uint _gid [[thread_position_in_grid]]")
        return f"kernel void {m.group(1)}({', '.join(out)})"
    body = re.sub(r"FORGE_GLOBAL void (forge_\w+)\(([^)]*)\)", sig, body, flags=re.S)
    # local pointers into device buffers
    body = re.sub(r"(?<![\w>])const float\* (xr|qp|kp|vp)\b", r"device const float* \1", body)
    body = re.sub(r"(?<![\w>])float\* (yr|yp)\b", r"device float* \1", body)
    return MSL_PRELUDE + body

