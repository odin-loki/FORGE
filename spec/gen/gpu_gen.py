#!/usr/bin/env python3
"""spec -> GPU kernels (FORGE_PLAN Part B.4: Vulkan/Metal kernels come from the spec generator).

Emits, for the spec ops that have a GPU lowering below:
  * one GLSL compute shader per kernel (compiled to SPIR-V by glslangValidator, validated by spirv-val,
    embedded into the binary and run through the Vulkan backend), and
  * one CUDA/HIP single-source file (compiled to PTX / AMDGCN by clang as a compile check).
Every emitted kernel must name an op present in spec/ops/*.fspec, so the GPU set can never drift from the spec.
"""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from fspec_gen import parse

# unary: GLSL expression, CUDA/HIP expression (x is the input; fx() helpers defined in the prelude)
UNARY = {
    "neg": ("-x", "-x"), "abs": ("abs(x)", "fabs_(x)"), "sqrt": ("sqrt(x)", "fsqrt(x)"),
    "rsqrt": ("inversesqrt(x)", "1.0f / fsqrt(x)"), "recip": ("1.0 / x", "1.0f / x"), "square": ("x * x", "x * x"),
    "exp": ("exp(x)", "fexp(x)"), "exp2": ("exp2(x)", "fexp2(x)"), "log": ("log(x)", "flog(x)"), "log2": ("log2(x)", "flog2(x)"),
    "sin": ("sin(x)", None), "cos": ("cos(x)", None), "tanh": ("tanh(x)", "ftanh(x)"),
    "sigmoid": ("1.0 / (1.0 + exp(-x))", "1.0f / (1.0f + fexp(-x))"), "silu": ("x / (1.0 + exp(-x))", "x / (1.0f + fexp(-x))"),
    "relu": ("max(x, 0.0)", "(x > 0.0f ? x : 0.0f)"),
    "softplus": ("max(x, 0.0) + log(1.0 + exp(-abs(x)))", "(x > 0.0f ? x : 0.0f) + flog(1.0f + fexp(-fabs_(x)))"),
    "gelu_tanh": ("0.5 * x * (1.0 + tanh(0.7978845608028654 * (x + 0.044715 * x * x * x)))",
                  "0.5f * x * (1.0f + ftanh(0.7978845608f * (x + 0.044715f * x * x * x)))"),
}
BINARY = {
    "add": ("a + b", "a + b"), "sub": ("a - b", "a - b"), "mul": ("a * b", "a * b"), "div": ("a / b", "a / b"),
    "maximum": ("(a > b ? a : b)", "(a > b ? a : b)"), "minimum": ("(a < b ? a : b)", "(a < b ? a : b)"),
}
OTHER = ["scale", "softmax", "rms_norm", "matmul_t", "silu_mul", "rope", "gather", "attention", "slice"]

GLSL_HEAD = """#version 450
// generated by spec/gen/gpu_gen.py from spec/ops -- do not edit
layout(local_size_x = 64) in;
// exp with Cody-Waite reduction + degree-6 polynomial (~1 ulp); GLSL exp() may be as loose as 3+2|x| ulp.
float fexp(float x) {
  if (x < -87.3) return 0.0;
  x = min(x, 88.7);
  float n = round(x * 1.4426950408889634);
  float r = fma(n, -0.693145751953125, x); r = fma(n, -1.428606765330187e-06, r);
  float p = fma(r, 1.0 / 720.0, 1.0 / 120.0); p = fma(p, r, 1.0 / 24.0); p = fma(p, r, 1.0 / 6.0);
  p = fma(p, r, 0.5); p = fma(p, r, 1.0); p = fma(p, r, 1.0);
  return ldexp(p, int(n));
}
layout(push_constant) uniform P { uint n; uint rows; uint cols; uint k; float alpha; uint a; uint b; uint c; uint d; float beta; } p;
"""

def glsl(name):
    if name in UNARY:
        return GLSL_HEAD + f"""layout(std430, binding = 0) readonly buffer X {{ float x_[]; }};
layout(std430, binding = 1) writeonly buffer Y {{ float y_[]; }};
void main() {{ uint i = gl_GlobalInvocationID.x; if (i >= p.n) return; float x = x_[i]; y_[i] = {UNARY[name][0]}; }}
"""
    if name in BINARY:
        return GLSL_HEAD + f"""layout(std430, binding = 0) readonly buffer A {{ float a_[]; }};
layout(std430, binding = 1) readonly buffer B {{ float b_[]; }};
layout(std430, binding = 2) writeonly buffer Y {{ float y_[]; }};
void main() {{ uint i = gl_GlobalInvocationID.x; if (i >= p.n) return; float a = a_[i]; float b = b_[i]; y_[i] = {BINARY[name][0]}; }}
"""
    if name == "scale":
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer X { float x_[]; };
layout(std430, binding = 1) writeonly buffer Y { float y_[]; };
void main() { uint i = gl_GlobalInvocationID.x; if (i >= p.n) return; y_[i] = p.alpha * x_[i]; }
"""
    if name == "silu_mul":
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer A { float a_[]; };
layout(std430, binding = 1) readonly buffer B { float b_[]; };
layout(std430, binding = 2) writeonly buffer Y { float y_[]; };
void main() { uint i = gl_GlobalInvocationID.x; if (i >= p.n) return; float a = a_[i]; y_[i] = a / (1.0 + exp(-a)) * b_[i]; }
"""
    if name == "softmax":  # one invocation per row
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer X { float x_[]; };
layout(std430, binding = 1) writeonly buffer Y { float y_[]; };
void main() {
  uint r = gl_GlobalInvocationID.x; if (r >= p.rows) return;
  uint o = r * p.cols; float m = x_[o];
  for (uint j = 1; j < p.cols; ++j) m = max(m, x_[o + j]);
  float s = 0.0; for (uint j = 0; j < p.cols; ++j) s += fexp(x_[o + j] - m);
  float inv = 1.0 / s; for (uint j = 0; j < p.cols; ++j) y_[o + j] = fexp(x_[o + j] - m) * inv;
}
"""
    if name == "rms_norm":
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer X { float x_[]; };
layout(std430, binding = 1) readonly buffer W { float w_[]; };
layout(std430, binding = 2) writeonly buffer Y { float y_[]; };
void main() {
  uint r = gl_GlobalInvocationID.x; if (r >= p.rows) return;
  uint o = r * p.cols; float s = 0.0;
  for (uint j = 0; j < p.cols; ++j) s += x_[o + j] * x_[o + j];
  float inv = inversesqrt(s / float(p.cols) + p.alpha);
  for (uint j = 0; j < p.cols; ++j) y_[o + j] = x_[o + j] * inv * w_[j];
}
"""
    if name == "matmul_t":  # y[rows, cols] = a[rows, k] @ b[cols, k]^T, one invocation per output
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer A { float a_[]; };
layout(std430, binding = 1) readonly buffer B { float b_[]; };
layout(std430, binding = 2) writeonly buffer Y { float y_[]; };
void main() {
  uint i = gl_GlobalInvocationID.x; if (i >= p.rows * p.cols) return;
  uint r = i / p.cols, c = i % p.cols; float s = 0.0;
  for (uint t = 0; t < p.k; ++t) s = fma(a_[r * p.k + t], b_[c * p.k + t], s);
  y_[i] = s;
}
"""
    if name == "rope":  # x[s,h,d], pos[s]; one invocation per rotated pair. push: rows=s, cols=h, k=d, a=neox, alpha=base
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer X { float x_[]; };
layout(std430, binding = 1) readonly buffer Q { float pos_[]; };
layout(std430, binding = 2) writeonly buffer Y { float y_[]; };
void main() {
  uint half_ = p.k / 2; uint i = gl_GlobalInvocationID.x; if (i >= p.rows * p.cols * half_) return;
  uint j = i % half_, row = i / half_, s = row / p.cols; uint o = row * p.k;
  float th = pos_[s] * pow(p.alpha, -2.0 * float(j) / float(p.k));
  float c = cos(th), sn = sin(th);
  uint i0 = p.a != 0u ? j : 2u * j, i1 = p.a != 0u ? j + half_ : 2u * j + 1u;
  float x0 = x_[o + i0], x1 = x_[o + i1];
  y_[o + i0] = x0 * c - x1 * sn; y_[o + i1] = x0 * sn + x1 * c;
}
"""
    if name == "gather":  # table[n, d], idx[m] -> [m, d]; push: n=m*d, cols=d, rows=n
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer T { float t_[]; };
layout(std430, binding = 1) readonly buffer I { float idx_[]; };
layout(std430, binding = 2) writeonly buffer Y { float y_[]; };
void main() {
  uint i = gl_GlobalInvocationID.x; if (i >= p.n) return;
  uint r = uint(idx_[i / p.cols]); y_[i] = r < p.rows ? t_[r * p.cols + i % p.cols] : 0.0;
}
"""
    if name == "attention":  # q[s,hq,d] k[t,hk,d] v[t,hk,dv]; one invocation per (query, head).
        # push: rows=s, cols=hq, k=d, a=t, b=hk, c=dv, d=causal | kcodec<<1 | vcodec<<3 | window<<5, alpha=scale
        # A quantised K/V (codec 1 int8, 2 fp8 e4m3) holds per (row, head) one f32 scale word + ceil(d/4)
        # words of packed bytes (flow/kv_codec.hpp); it is decoded here on the fly.
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer Qb { float q_[]; };
layout(std430, binding = 1) readonly buffer Kb { float k_[]; };
layout(std430, binding = 2) readonly buffer Vb { float v_[]; };
layout(std430, binding = 3) buffer Y { float y_[]; };
float fp8dec(uint b) {
  uint e = (b >> 3) & 15u, m = b & 7u;
  float v = e == 0u ? ldexp(float(m), -9) : ldexp(float(8u + m), int(e) - 10);
  return (b & 0x80u) != 0u ? -v : v;
}
float qdec(uint codec, uint word, uint e) {
  uint b = (word >> (8u * (e & 3u))) & 255u;
  return codec == 1u ? float(int(b << 24) >> 24) : fp8dec(b);
}
float kat(uint kc, uint base, uint e) {
  if (kc == 0u) return k_[base + e];
  return qdec(kc, floatBitsToUint(k_[base + 1u + (e >> 2)]), e) * k_[base];
}
float vat(uint vc, uint base, uint e) {
  if (vc == 0u) return v_[base + e];
  return qdec(vc, floatBitsToUint(v_[base + 1u + (e >> 2)]), e) * v_[base];
}
// 4 partial sums (like the CPU lane dot) keep the score error well inside the oracle's 1e-5.
float qk(uint kc, uint qo, uint ko) {
  vec4 acc = vec4(0.0); uint e = 0;
  for (; e + 4u <= p.k; e += 4u) acc = fma(vec4(q_[qo+e], q_[qo+e+1u], q_[qo+e+2u], q_[qo+e+3u]), vec4(kat(kc,ko,e), kat(kc,ko,e+1u), kat(kc,ko,e+2u), kat(kc,ko,e+3u)), acc);
  float s = (acc.x + acc.y) + (acc.z + acc.w);
  for (; e < p.k; ++e) s = fma(q_[qo + e], kat(kc, ko, e), s);
  return s;
}
void main() {
  uint id = gl_GlobalInvocationID.x; if (id >= p.rows * p.cols) return;
  uint i = id / p.cols, h = id % p.cols, kh = h / (p.cols / p.b);
  bool causal = (p.d & 1u) != 0u; uint kc = (p.d >> 1) & 3u, vc = (p.d >> 3) & 3u, window = p.d >> 5;
  uint kw = kc == 0u ? p.k : 1u + (p.k + 3u) / 4u, vw = vc == 0u ? p.c : 1u + (p.c + 3u) / 4u;
  int pos = int(p.a) - int(p.rows) + int(i);
  uint qo = id * p.k, yo = id * p.c;
  float m = -1.0 / 0.0;
  for (uint j = 0; j < p.a; ++j) {
    if (causal && int(j) > pos) continue; if (window > 0u && pos - int(j) >= int(window)) continue;
    float dot = qk(kc, qo, (j * p.b + kh) * kw);
    m = max(m, dot * p.alpha);
  }
  for (uint e = 0; e < p.c; ++e) y_[yo + e] = 0.0;
  float sum = 0.0;
  for (uint j = 0; j < p.a; ++j) {
    if (causal && int(j) > pos) continue; if (window > 0u && pos - int(j) >= int(window)) continue;
    float dot = qk(kc, qo, (j * p.b + kh) * kw);
    float w = fexp(dot * p.alpha - m); sum += w;
    for (uint e = 0; e < p.c; ++e) y_[yo + e] += w * vat(vc, (j * p.b + kh) * vw, e);
  }
  float inv = sum > 0.0 ? 1.0 / sum : 0.0;
  for (uint e = 0; e < p.c; ++e) y_[yo + e] *= inv;
}
"""
    if name == "slice":  # x viewed as [outer, n, inner] -> [outer, len, inner] from `start`; push: cols=n, k=inner, a=start, b=len
        return GLSL_HEAD + """layout(std430, binding = 0) readonly buffer X { float x_[]; };
layout(std430, binding = 1) writeonly buffer Y { float y_[]; };
void main() {
  uint i = gl_GlobalInvocationID.x; if (i >= p.n) return;
  uint in_ = i % p.k, r = (i / p.k) % p.b, o = i / (p.k * p.b);
  y_[i] = x_[(o * p.cols + p.a + r) * p.k + in_];
}
"""
    raise KeyError(name)

CU_PRELUDE = r"""// generated by spec/gen/gpu_gen.py from spec/ops -- do not edit
// Header-free CUDA/HIP single source: compiled with clang --cuda-device-only (-nocudainc / -nogpuinc).
#define FORGE_GLOBAL extern "C" __attribute__((global))
#define FORGE_DEV static __attribute__((device)) inline
#if defined(__NVPTX__)
FORGE_DEV unsigned gid() { return __nvvm_read_ptx_sreg_ctaid_x() * __nvvm_read_ptx_sreg_ntid_x() + __nvvm_read_ptx_sreg_tid_x(); }
FORGE_DEV float fexp2(float x) { return __nvvm_ex2_approx_f(x); }
FORGE_DEV float flog2(float x) { return __nvvm_lg2_approx_f(x); }
FORGE_DEV float fsqrt(float x) { return __nvvm_sqrt_rn_f(x); }
FORGE_DEV float fma_(float a, float b, float c) { return __nvvm_fma_rn_f(a, b, c); }
#elif defined(__AMDGPU__)
FORGE_DEV unsigned gid() { return __builtin_amdgcn_workgroup_id_x() * __builtin_amdgcn_workgroup_size_x() + __builtin_amdgcn_workitem_id_x(); }
FORGE_DEV float fexp2(float x) { return __builtin_amdgcn_exp2f(x); }
FORGE_DEV float flog2(float x) { return __builtin_amdgcn_logf(x); }
FORGE_DEV float fsqrt(float x) { return __builtin_amdgcn_sqrtf(x); }
FORGE_DEV float fma_(float a, float b, float c) { return __builtin_fmaf(a, b, c); }
#else
#error "compile with --cuda-device-only for nvptx or amdgcn"
#endif
FORGE_DEV float fabs_(float x) { return x < 0.0f ? -x : x; }
FORGE_DEV float fexp(float x) { return fexp2(x * 1.4426950408889634f); }
FORGE_DEV float flog(float x) { return flog2(x) * 0.6931471805599453f; }
FORGE_DEV float ftanh(float x) { float e = fexp(-2.0f * fabs_(x)); float t = (1.0f - e) / (1.0f + e); return x < 0.0f ? -t : t; }
"""

def cuda(names):
    out = [CU_PRELUDE]
    for n in names:
        if n in UNARY and UNARY[n][1]:
            out.append(f"FORGE_GLOBAL void forge_{n}(const float* x_, float* y_, unsigned n) {{ unsigned i = gid(); if (i >= n) return; float x = x_[i]; y_[i] = {UNARY[n][1]}; }}")
        elif n in BINARY:
            out.append(f"FORGE_GLOBAL void forge_{n}(const float* a_, const float* b_, float* y_, unsigned n) {{ unsigned i = gid(); if (i >= n) return; float a = a_[i]; float b = b_[i]; y_[i] = {BINARY[n][1]}; }}")
    out.append("FORGE_GLOBAL void forge_scale(const float* x, float* y, unsigned n, float alpha) { unsigned i = gid(); if (i < n) y[i] = alpha * x[i]; }")
    out.append("FORGE_GLOBAL void forge_silu_mul(const float* a, const float* b, float* y, unsigned n) { unsigned i = gid(); if (i < n) y[i] = a[i] / (1.0f + fexp(-a[i])) * b[i]; }")
    out.append("""FORGE_GLOBAL void forge_softmax(const float* x, float* y, unsigned rows, unsigned cols) {
  unsigned r = gid(); if (r >= rows) return; const float* xr = x + r * cols; float* yr = y + r * cols;
  float m = xr[0]; for (unsigned j = 1; j < cols; ++j) m = xr[j] > m ? xr[j] : m;
  float s = 0.0f; for (unsigned j = 0; j < cols; ++j) s += fexp(xr[j] - m);
  for (unsigned j = 0; j < cols; ++j) yr[j] = fexp(xr[j] - m) / s; }""")
    out.append("""FORGE_GLOBAL void forge_rms_norm(const float* x, const float* w, float* y, unsigned rows, unsigned cols, float eps) {
  unsigned r = gid(); if (r >= rows) return; const float* xr = x + r * cols; float s = 0.0f;
  for (unsigned j = 0; j < cols; ++j) s += xr[j] * xr[j];
  float inv = 1.0f / fsqrt(s / float(cols) + eps); for (unsigned j = 0; j < cols; ++j) y[r * cols + j] = xr[j] * inv * w[j]; }""")
    out.append("""FORGE_GLOBAL void forge_matmul_t(const float* a, const float* b, float* y, unsigned rows, unsigned cols, unsigned k) {
  unsigned i = gid(); if (i >= rows * cols) return; unsigned r = i / cols, c = i % cols; float s = 0.0f;
  for (unsigned t = 0; t < k; ++t) s = fma_(a[r * k + t], b[c * k + t], s); y[i] = s; }""")
    return "\n".join(out) + "\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ops", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--list", action="store_true", help="print kernel names and exit")
    ap.add_argument("--embed", metavar="HEADER", help="embed <out>/<name>.spv into HEADER and exit")
    ap.add_argument("--embed-images", metavar="HEADER", help="embed the PTX / AMDGPU code objects given as files into HEADER")
    ap.add_argument("images", nargs="*", help="kernels.ptx and kernels.<gfxNNN>.hsaco files (with --embed-images)")
    a = ap.parse_args()
    spec = {o["name"] for f in a.ops for o in parse(f)}
    names = sorted(UNARY) + sorted(BINARY) + OTHER
    missing = [n for n in names if n not in spec]
    if missing: sys.exit(f"gpu_gen: kernels for ops not in the spec: {missing}")
    if a.list: print(";".join(names)); return
    if a.embed: embed(a.out, names, a.embed); return
    if a.embed_images: embed_images(a.images, a.embed_images); return
    os.makedirs(a.out, exist_ok=True)
    def put(path, text):
        if not os.path.exists(path) or open(path).read() != text: open(path, "w").write(text)
    for n in names: put(os.path.join(a.out, n + ".comp"), glsl(n))
    put(os.path.join(a.out, "kernels.cu"), cuda(names))
    put(os.path.join(a.out, "kernels.list"), ";".join(names))



def embed(spv_dir, names, out):
    """Write a header embedding <name>.spv for each kernel (used by grid/vulkan.hpp)."""
    lines = ["// generated by spec/gen/gpu_gen.py -- do not edit", "#pragma once", "#include <cstddef>", "#include <cstdint>",
             "namespace forge::grid::spv {"]
    table = []
    for n in names:
        data = open(os.path.join(spv_dir, n + ".spv"), "rb").read()
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        lines.append(f"inline constexpr std::uint32_t {n}_words[] = {{" + ",".join(hex(w) for w in words) + "};")
        table.append(f'{{"{n}", {n}_words, {len(words)}}}')
    lines += ["struct blob { const char* name; const std::uint32_t* words; std::size_t count; };",
              f"inline constexpr blob table[] = {{{', '.join(table)}}};", "} // namespace forge::grid::spv", ""]
    text = "\n".join(lines)
    if not os.path.exists(out) or open(out).read() != text: open(out, "w").write(text)

def embed_images(files, out):
    """Write a header with the CUDA PTX and HIP code objects (used by grid/cuda.hpp); missing ones are empty."""
    def arr(name, data):
        return f"inline constexpr unsigned char {name}[] = {{" + ",".join(str(b) for b in data) + ",0};"
    ptx = b""; hsaco = []
    for f in files:
        if not os.path.exists(f): continue
        base = os.path.basename(f)
        if base.endswith(".ptx"): ptx = open(f, "rb").read()
        elif base.endswith(".hsaco"): hsaco.append((base.split(".")[1], open(f, "rb").read()))
    lines = ["// generated by spec/gen/gpu_gen.py -- do not edit", "#pragma once", "#include <cstddef>",
             "namespace forge::grid::gpu::images {",
             "inline constexpr char ptx[] = {" + ",".join(str(b if b < 128 else b - 256) for b in ptx) + ",0};",
             f"inline constexpr std::size_t ptx_size = {len(ptx)};"]
    for arch, d in hsaco: lines.append(arr(f"hsaco_{arch}", d))
    lines.append("struct code_object { const char* arch; const unsigned char* data; std::size_t size; };")
    entries = ", ".join(f'{{"{a}", hsaco_{a}, {len(d)}}}' for a, d in hsaco) or '{"", nullptr, 0}'
    lines += [f"inline constexpr code_object hsaco[] = {{{entries}}};", f"inline constexpr std::size_t hsaco_count = {len(hsaco)};",
              "} // namespace forge::grid::gpu::images", ""]
    text = "\n".join(lines)
    if not os.path.exists(out) or open(out).read() != text: open(out, "w").write(text)

if __name__ == "__main__":
    main()
