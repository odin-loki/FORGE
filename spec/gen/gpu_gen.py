def opencl(names):
    import re
    body = cuda(names)
    body = body[body.index(CU_MATH):].replace(CU_MATH, "") if False else body
    body = body.replace(CU_PRELUDE, "").replace(CU_MATH, "")
    body = re.sub(r"(?<![\w])(const float\*|float\*)", lambda m: "G " + m.group(1), body)
    body = body.replace("FORGE_GLOBAL void", "FORGE_K void").replace("FORGE_DEV", "static inline")
    body = body.replace("__builtin_bit_cast(unsigned, ", "as_uint(").replace("-__builtin_inff()", "-INFINITY")
    body = body.replace("double th = (double)pos[s] * (double)inv[j]", "FORGE_ANGLE th = (FORGE_ANGLE)pos[s] * (FORGE_ANGLE)inv[j]")
    return CL_PRELUDE + body

def cl_mock_dispatch(names):
    """C trampolines for tests/mock_opencl.c: call each kernel with arguments from clSetKernelArg slots."""
    import re
    out = ["// generated by spec/gen/gpu_gen.py -- do not edit", "typedef void (*forge_tramp)(void** a);"]
    table = []
    for m in re.finditer(r"FORGE_K void (forge_\w+)\(([^)]*)\)", opencl(names)):
        fn, params = m.group(1), [p.strip() for p in m.group(2).split(",")]
        args = []
        for i, p in enumerate(params):
            if "*" in p: args.append(f"(float*)MOCK_MEM(a[{i}])")
            elif p.startswith("float"): args.append(f"*(float*)a[{i}]")
            else: args.append(f"*(unsigned*)a[{i}]")
        out.append(f"static void t_{fn}(void** a) {{ {fn}({', '.join(args)}); }}")
        table.append(f'  {{"{fn}", t_{fn}, {len(params)}}},')
    out.append("static const struct { const char* name; forge_tramp f; int nargs; } forge_tramps[] = {")
    out += table + ["  {0, 0, 0}};"]
    return "\n".join(out) + "\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ops", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--list", action="store_true", help="print kernel names and exit")
    ap.add_argument("--embed", metavar="HEADER", help="embed <out>/<name>.spv into HEADER and exit")
    ap.add_argument("--embed-images", metavar="HEADER", help="embed the PTX / AMDGPU code objects given as files into HEADER")
    ap.add_argument("images", nargs="*", help="kernels.ptx and kernels.<gfxNNN>.hsaco files (with --embed-images)")
    a = ap.parse_args()
    spec = {o["name"] for f in a.ops for o in parse(f)}
    names = sorted(UNARY) + sorted(BINARY) + OTHER
    missing = [n for n in names if n not in spec]
    if missing: sys.exit(f"gpu_gen: kernels for ops not in the spec: {missing}")
    if a.list: print(";".join(names)); return
    if a.embed: embed(a.out, names, a.embed); return
