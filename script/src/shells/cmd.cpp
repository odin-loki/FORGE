// cmd.exe: backend + emitter (batch file with delayed expansion). UNTESTED: no Windows or wine on the
// FORGE CI box. No functions (only `int main()` is inlined), no loops inside if/for blocks, no
// fs.read and no forge::sh/shell results: those are emit errors.
#include "shell.hpp"
#include "emit_dialect.hpp"
namespace {
using namespace forge::script;
// String fragments are raw batch text, escaped for use inside "..." with delayed expansion on.
std::string bq(const std::string& s) { std::string o; for (char c : s) { if (c == '%') o += "%%"; else if (c == '!') o += "^^!"; else if (c == '"') o += "\"\""; else if (c == '\n' || c == '\r') throw emit_error(0, "newlines in cmd string literals"); else o += c; } return o; }
struct cmd_dialect : block_dialect {
    int parens = 0, label = 0;
    std::vector<int> loops;
    cmd_dialect() { has_functions = false; noop = "rem"; }
    std::string header() override { return "@echo off\r\nrem generated by `forge script --emit cmd`; runs without FORGE (UNTESTED target)\r\nsetlocal EnableExtensions EnableDelayedExpansion\r\n"; }
    std::string footer() override { return "endlocal\r\n"; }
    std::string tmp_int(const std::string& e) { auto t = cx->tmp(); L("set /a " + t + "=" + e); return "!" + t + "!"; }
    std::string s_lit(const std::string& s) override { return bq(s); }
    std::string i_lit(long long v) override { return std::to_string(v); }
    std::string ref(const std::string& n, ety, bool) override { return "!" + n + "!"; }
    std::string arith(char op, const std::string& a, const std::string& b) override { return tmp_int("(" + a + ")" + (op == '%' ? std::string("%%") : std::string(1, op)) + "(" + b + ")"); }
    std::string concat(const std::vector<std::string>& p) override { std::string o; for (auto& x : p) o += x; return o; }
    std::string i2s(const std::string& i) override { return i; }
    std::string s2i(const std::string& s) override { return tmp_int(s); }
    std::string slen(const std::string&) override { no(".size()"); }
    std::string cmp(const std::string& op, const std::string& a, const std::string& b, bool ints) override {
        static const std::pair<const char*, const char*> io[] = {{"==", "EQU"}, {"!=", "NEQ"}, {"<", "LSS"}, {"<=", "LEQ"}, {">", "GTR"}, {">=", "GEQ"}};
        if (ints) for (auto& [o, t] : io) if (op == o) return a + " " + t + " " + b;
        if (op == "==") return "\"" + a + "\"==\"" + b + "\"";
        if (op == "!=") return "not \"" + a + "\"==\"" + b + "\"";
        no("string ordering with " + op);
    }
    std::string c_and(const std::string&, const std::string&) override { return ""; }
    std::string c_or(const std::string&, const std::string&) override { return ""; }
    std::string c_not(const std::string& a) override { if (a.starts_with("not ")) return a.substr(4); return "not " + a; }
    std::string c_bool(bool v) override { return v ? "1==1" : "1==0"; }
    std::string truthy(const std::string& v) override { return "\"" + v + "\"==\"true\""; }
    void let(const std::string& n, const std::string& v, ety t, bool, bool) override { L(t == ety::Int ? "set /a " + n + "=" + v : "set \"" + n + "=" + v + "\""); }
    void print(const std::string& v, bool nl, bool err) override { L((nl ? "echo(" + v : "<nul set /p \"=" + v + "\"") + (err ? " 1>&2" : "")); }
    void if_(const std::string& c) override { open("if " + c + " ("); ++parens; }
    void else_() override { mid(") else ("); }
    void end_if() override { close(")"); --parens; }
    void while_(const std::string& c) override {
        if (parens) no("a loop nested inside an if or for block");
        int l = ++label; loops.push_back(l);
        L(":w" + std::to_string(l)); L("if not " + c + " goto w" + std::to_string(l) + "e");
        opens.push_back(cx->lines.size()); in();
    }
    void end_while() override { int l = loops.back(); loops.pop_back(); L("goto w" + std::to_string(l)); opens.pop_back(); out(); L(":w" + std::to_string(l) + "e"); }
    void for_(const std::string& v, const std::vector<std::string>& items) override {
        std::string s; for (auto& i : items) s += (s.empty() ? "\"" : " \"") + i + "\"";
        open("for %%_" + v + " in (" + s + ") do ("); ++parens; loops.push_back(0);
        L("set \"" + v + "=%%~_" + v + "\"");
    }
    void end_for() override { loops.pop_back(); close(")"); --parens; }
    void brk() override { if (loops.empty() || loops.back() == 0) no("break inside a for loop"); L("goto w" + std::to_string(loops.back()) + "e"); }
    void cont() override { if (loops.empty() || loops.back() == 0) no("continue inside a for loop"); L("goto w" + std::to_string(loops.back())); }
    void fn_(const std::string&, const std::vector<std::string>&) override { no("functions"); }
    void end_fn() override {}
    void ret(const std::string&) override { no("return"); }
    std::string call(const std::string& name, const std::vector<std::string>&, bool, ety) override { no("calling " + name); }
    void exit_(const std::string& c) override { L("exit /b " + c); }
    std::string env(const std::string& n, const std::string& d) override {
        auto t = cx->tmp(); L("set \"" + t + "=" + d + "\"");
        L("if defined " + n + " set \"" + t + "=!" + n + "!\"");
        return "!" + t + "!";
    }
    void setenv(const std::string& n, const std::string& v) override { L("set \"" + n + "=" + v + "\""); }
    std::string test_path(const std::string& p, char k) override {
        if (k == 'd') return "exist \"" + p + "\\*\"";
        if (k == 'f') { auto t = cx->tmp(); L("set \"" + t + "=false\""); L("if exist \"" + p + "\" if not exist \"" + p + "\\*\" set \"" + t + "=true\""); return truthy("!" + t + "!"); }
        return "exist \"" + p + "\"";
    }
    void mkdir(const std::string& p) override { L("mkdir \"" + p + "\" 2>nul"); }
    void remove(const std::string& p) override { L("if exist \"" + p + "\\*\" (rmdir /s /q \"" + p + "\") else if exist \"" + p + "\" del /q \"" + p + "\""); }
    void write(const std::string& p, const std::string& s, bool app) override { L("<nul set /p \"=" + s + "\"" + (app ? " >> \"" : " > \"") + p + "\""); }
    std::string read(const std::string&) override { no("fs.read"); }
    std::string cwd() override { return "!CD!"; }
    std::string platform() override { return "windows"; }
    void run(const std::string&, const std::string&, const std::string&, bool) override { no("forge::sh / forge::shell results"); }
    std::string sh_quote(const std::string&) override { no("forge::sh"); }
};
} // namespace
void forge_shell_register_cmd(forge::script::shell_registry& r) {
    forge::script::shell_backend b; b.name = "cmd"; b.exes = {"cmd.exe", "cmd"}; b.family = "cmd"; b.notes = "Windows only (wine in CI)";
    b.argv = [](const std::string& exe, const std::string& sc) -> std::vector<std::string> { return {exe, "/d", "/s", "/c", sc}; };
    b.quote = [](const std::string& s) { std::string o = "\""; for (char c : s) { if (c == '"') o += "\"\""; else if (c == '%') o += "%%"; else o += c; } return o + "\""; };
    b.emitter = [] { return std::make_unique<cmd_dialect>(); }; b.emit_ext = ".cmd";
    r.add(std::move(b));
}
