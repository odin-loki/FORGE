#!/usr/bin/env python3
"""The three declarations of the JNI surface must agree:

  bindings/android/forge/src/main/kotlin/dev/forge/ForgeNative.kt   the Kotlin externals (never compiled here)
  tests/jni/dev/forge/ForgeNative.java                              the Java mirror the host-JVM test runs (jni_smoke)
  bindings/android/jni/forge_jni.c                                  the C functions

This reads the Kotlin `@JvmStatic external fun` lines, derives the Java declaration and each function's JNI
parameter list from them, and fails when the Java file or the C file differs. `--write` regenerates the Java file.

  jni_decl_check.py <repo root> [--write]
"""
import os, re, sys
root = sys.argv[1]
kt = open(os.path.join(root, "bindings/android/forge/src/main/kotlin/dev/forge/ForgeNative.kt")).read()
java_path = os.path.join(root, "tests/jni/dev/forge/ForgeNative.java")
c_src = open(os.path.join(root, "bindings/android/jni/forge_jni.c")).read()

JAVA = {"String": "String", "Int": "int", "Long": "long", "Boolean": "boolean", "Float": "float", "ByteArray": "byte[]", "IntArray": "int[]",
        "FloatArray": "float[]", "LongArray": "long[]", "Array<ByteArray>": "byte[][]", "TokenSink": "TokenSink", "DoneSink": "DoneSink"}
JNI = {"String": "jstring", "Int": "jint", "Long": "jlong", "Boolean": "jboolean", "Float": "jfloat", "ByteArray": "jbyteArray", "IntArray": "jintArray",
       "FloatArray": "jfloatArray", "LongArray": "jlongArray", "Array<ByteArray>": "jobjectArray", "TokenSink": "jobject", "DoneSink": "jobject", None: "void"}

decls = []   # (name, [(param name, kotlin type)], kotlin return type or None)
for m in re.finditer(r"@JvmStatic external fun (\w+)\(([^)]*)\)(?:: ([\w<>]+))?", kt, re.S):
    params = []
    for p in [x.strip() for x in m.group(2).replace("\n", " ").split(",") if x.strip()]:
        n, t = [y.strip() for y in p.split(":")]
        params.append((n, t.rstrip("?")))
    decls.append((m.group(1), params, m.group(3)))
if len(decls) < 50: raise SystemExit(f"only {len(decls)} externals found in ForgeNative.kt: the pattern no longer matches")

lines = [f"    public static native {JAVA[r] if r else 'void'} {n}({', '.join(f'{JAVA[t]} {pn}' for pn, t in ps)});" for n, ps, r in decls]
java = '''package dev.forge;

/**
 * Java declaration of the natives in bindings/android/jni/forge_jni.c, for the host-JVM test of the JNI bridge
 * (tests/jni/JniSmoke.java, ctest jni_smoke). It mirrors the Kotlin object dev.forge.ForgeNative
 * (bindings/android/forge/src/main/kotlin/dev/forge/ForgeNative.kt) method for method.
 * GENERATED by tests/jni_decl_check.py --write from the Kotlin file; ctest jni_decl_matches fails when they differ.
 */
public final class ForgeNative {
    static { System.loadLibrary("forge_jni"); }
    private ForgeNative() {}

    public interface TokenSink { boolean onTokenBytes(int token, byte[] text); }
    public interface DoneSink { void onDoneBytes(long id, int[] tokens, byte[] reason); }

''' + "\n".join(lines) + "\n}\n"
if "--write" in sys.argv:
    os.makedirs(os.path.dirname(java_path), exist_ok=True)
    open(java_path, "w").write(java)
elif open(java_path).read() != java:
    raise SystemExit("tests/jni/dev/forge/ForgeNative.java does not match ForgeNative.kt: run tests/jni_decl_check.py <root> --write")

# the C side: every external has one NAT(name) definition with the matching JNI types, and there are no others
c_funcs = {}
for m in re.finditer(r"JNIEXPORT (\w+) JNICALL NAT\((\w+)\)\(JNIEnv\* env, jclass c((?:,[^)]*)?)\)", c_src, re.S):
    types = [" ".join(p.split()[:-1]) for p in m.group(3).replace("\n", " ").split(",") if p.strip()]
    c_funcs[m.group(2)] = (m.group(1), types)
bad = []
for n, ps, r in decls:
    want = (JNI[r], [JNI[t] for _, t in ps])
    if c_funcs.get(n) != want: bad.append(f"{n}: Kotlin wants {want}, forge_jni.c has {c_funcs.get(n)}")
for n in sorted(set(c_funcs) - {d[0] for d in decls}): bad.append(f"{n}: defined in forge_jni.c, not declared in ForgeNative.kt")
if bad: raise SystemExit("JNI declarations differ:\n  " + "\n  ".join(bad))
# the callback methods the C side looks up by name and signature
for needle in ('"onTokenBytes", "(I[B)Z"', '"onDoneBytes", "(J[I[B)V"'):
    if needle not in c_src: raise SystemExit(f"forge_jni.c no longer looks up {needle}")
for needle in ("fun onTokenBytes(token: Int, text: ByteArray): Boolean", "fun onDoneBytes(id: Long, tokens: IntArray, reason: ByteArray)"):
    if needle not in kt: raise SystemExit(f"ForgeNative.kt no longer declares `{needle}`")
print(f"jni declarations agree: {len(decls)} natives")
